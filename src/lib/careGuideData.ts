/**
 * 일상 관리 가이드 (양치·털관리·미용·발톱·귀·목욕 등).
 * 외부 DB가 아닌 큐레이션 정적 데이터로 관리한다. (수의/미용 일반 권장사항 기반)
 * 종(species)·나이단계(lifeStage)·크기(size)별로 표시를 구분한다.
 */

export type CareGuideStage = '퍼피·키튼' | '성견·성묘' | '시니어' | '공통'

export interface CareGuideTopic {
  id: string
  icon: string
  topic: string
  /** 'both' = 강아지·고양이 공통 */
  species: Species | 'both'
  /** 권장 주기 한 줄 요약 */
  frequency: string
  /** 단계별 안내. stage가 '공통'이면 모든 나이에 적용 */
  notes: {
    stage: CareGuideStage
    /** 특정 크기에만 해당하면 표시 (없으면 전체) */
    size?: '소형' | '중형' | '대형'
    text: string
  }[]
  /** 방법 단계 */
  steps?: string[]
  /** 추가 팁 */
  tips?: string[]
}

