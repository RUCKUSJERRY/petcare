import type { Species } from '@/types'

/**
 * 증상별 대처 가이드 — "지금 토했는데/설사하는데 어떡하지?"처럼 보호자가 급하게 찾는 순간을
 * 위한 큐레이션 정적 정보. 예방 중심의 healthChecklist 와 달리 '증상 발생 후 대응'을 다룬다.
 *
 * ⚠ 수의학적 진단·처방이 아니라 일반 정보다. 응급 신호(redFlags)는 지체 없이 병원으로.
 *   투약·용량 안내는 담지 않는다(오남용 위험). 화면 상단에 디스클레이머를 함께 노출한다.
 */
export interface SymptomGuide {
  id: string
  icon: string
  /** 증상명 */
  title: string
  /** 'both' = 강아지·고양이 공통 */
  species: Species | 'both'
  /** 한 줄 요약(카드 접힘 상태에서 노출) */
  summary: string
  /** 집에서 관찰·케어할 것 */
  watch: string[]
  /** 즉시 병원이 필요한 위험 신호(적신호) */
  redFlags: string[]
  /** 병원 방문 판단 기준 한 줄 */
  vetWhen: string
}

/** 종 필터: 해당 종 + 공통(both). species 미지정 시 전체. */
export function symptomGuidesForSpecies(species?: Species | null): SymptomGuide[] {
  if (!species) return SYMPTOM_GUIDES
  return SYMPTOM_GUIDES.filter(g => g.species === 'both' || g.species === species)
}

/** 검색 매칭 — 증상명·요약·관찰/적신호 텍스트를 소문자로 훑는다(빈 질의는 항상 매칭). */
export function symptomGuideMatches(g: SymptomGuide, q: string): boolean {
  if (!q) return true
  const hay = `${g.title} ${g.summary} ${g.watch.join(' ')} ${g.redFlags.join(' ')} ${g.vetWhen}`
  return hay.toLowerCase().includes(q)
}

