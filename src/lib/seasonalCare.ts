/**
 * 월(1~12)로 계절을 판정한다. 12·1·2 겨울 / 3~5 봄 / 6~8 여름 / 9~11 가을.
 * (기상학적 계절 구분 — KST 달력 월 기준. 정상 입력은 1~12이며, 벗어나면 방어적으로 겨울로 폴백.)
 */
export function seasonForMonth(month: number): Season {
  if (month >= 3 && month <= 5) return 'spring'
  if (month >= 6 && month <= 8) return 'summer'
  if (month >= 9 && month <= 11) return 'autumn'
  return 'winter'
}

/**
 * 종·월에 맞는 계절 케어 포인트. 종 공통 포인트 뒤에 종별 포인트를 이어 붙인다.
 * @param month 1~12 (KST 달력 월)
 */
export function seasonalCareFor(species: Species, month: number): SeasonalCare {
  const season = seasonForMonth(month)
  const s = SEASONS[season]
  const extra = species === 'cat' ? s.cat : s.dog
  return { season, label: s.label, icon: s.icon, points: [...s.common, ...extra] }
}
